    /// <summary>翻译。中文模式直接返回原文；英文模式查不到回退原文（老项目 Case Else 语义）。</summary>
    public static string Tr(string zh)
    {
        if (CurrentLanguage == "CH")
            return zh;
        return En.TryGetValue(zh, out string? en) ? en : zh;
    }
